def decimal_to_binary(number, bit_counter=0):
    """
    Переводит целое неотрицательное число в двоичную запись (строкой).

    Алгоритм: число делится на 2 в цикле, остатки (0 или 1) собираются в
    список, а bit_counter считает, сколько цифр набралось. Список
    разворачивается ТОЛЬКО если bit_counter в конце больше 10.

    ВНИМАНИЕ, подвох: из-за этого для чисел до 1023 включительно (не более
    10 двоичных цифр) цифры получаются в обратном порядке, то есть
    decimal_to_binary(10) вернёт '0101', а не правильное '1010'. Верный
    порядок получается только для чисел от 1024 (11+ цифр) либо если
    передать большой начальный bit_counter.

    Для 0 и отрицательных чисел цикл не выполняется и возвращается "0".

    Args:
        number (int): число для перевода (ожидается >= 0)
        bit_counter (int): начальное значение счётчика цифр, по умолчанию 0.
            Влияет на то, развернётся ли результат (см. выше)

    Returns:
        str: строка из символов '0' и '1'

    Пример:
        >>> decimal_to_binary(10)
        '0101'
        >>> decimal_to_binary(10, 7)
        '1010'
        >>> decimal_to_binary(1024)
        '10000000000'
        >>> decimal_to_binary(0)
        '0'
    """
    binary_digits = []  # остатки от деления на 2 (младший разряд первым)

    while number > 0:
        binary_digits.append(number % 2)
        number = number // 2
        bit_counter += 1  # считаем, сколько двоичных цифр получилось
    if bit_counter > 10:
        binary_digits.reverse()
    return ''.join(map(str, binary_digits)) if binary_digits else "0"

print(decimal_to_binary(10))