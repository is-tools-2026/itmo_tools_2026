# Функция 1

def calculater(money, price_per_item, items_count):
    """
    Считает сдачу после покупки нескольких одинаковых товаров.

    Общая стоимость = price_per_item * items_count. Если денег хватает,
    возвращается сдача, если нет - текст с сообщением об ошибке.

    Args:
        money (int | float): сколько денег у покупателя
        price_per_item (int | float): цена одного товара
        items_count (int): количество товаров

    Returns:
        int | float | str: сдача (money - стоимость), если денег хватило
            (0, если хватило ровно); строка "Недостаточно денег", если не хватило

    Нюансы:
        Функция возвращает РАЗНЫЕ типы (число или строку), поэтому перед
        арифметикой с результатом нужно проверить тип. Налоги не учитываются.

    Пример:
        >>> calculater(100, 10, 5)
        50
        >>> calculater(50, 10, 5)
        0
        >>> calculater(20, 10, 5)
        'Недостаточно денег'
    """
    # Выдаёт сдачу. Налоги не включены: их никто не любит, даже эта функция.
    total = price_per_item * items_count
    if total > money:
        # "Денег нет, но вы держитесь" — философская позиция функции.
        return "Недостаточно денег"
    return money - total

print(calculater(100, 10, 5))

