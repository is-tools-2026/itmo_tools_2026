def buy_products(money, price_per_item, items_count):
    """
    Считает сдачу: сколько денег останется после покупки.
    Если денег не хватает, говорит об этом текстом.

    Args:
        money (int | float): сколько денег у покупателя
        price_per_item (int | float): цена одного товара
        items_count (int): сколько штук покупаем

    Returns:
        int | float | str: сдача, а если не хватает денег, то строка
        "Недостаточно денег". Если денег хватает впритык, сдача будет 0.

    Пример:
        >>> buy_products(100, 10, 5)
        50
        >>> buy_products(10, 10, 5)
        'Недостаточно денег'
    
    """
    # Выдаёт сдачу. Налоги не включены: их никто не любит, даже эта функция.
    total = price_per_item * items_count
    if total > money:
        # "Денег нет, но вы держитесь" — философская позиция функции.
        return "Недостаточно денег"
    return money - total

print(buy_products(100, 10, 5))

