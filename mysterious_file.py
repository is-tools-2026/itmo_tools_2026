def is_weekend(day_name):
    """
    Проверяет, является ли день недели выходным (суббота или воскресенье).

    Понимает только русские названия: "сб", "вс", "суббота", "воскресенье".
    Регистр не важен ("Суббота" и "СУББОТА" подойдут). Любое другое
    написание (например "Saturday" или "субб") даст False.

    Args:
        day_name (str): название дня недели на русском

    Returns:
        bool: True, если день выходной, иначе False

    Raises:
        AttributeError: если передана не строка (например число)

    Пример:
        >>> is_weekend("Суббота")
        True
        >>> is_weekend("пн")
        False
    """
    # Надо подать прошение на включение Пятницы.
    return day_name.lower() in ["сб", "вс", "суббота", "воскресенье"]

print(is_weekend("Суббота"))

