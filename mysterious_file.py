def calculater(money, price_per_item, items_count):
# ----------------------------------------------------------------------------------
    """
    считает сдачу после каждой покупки нескольких товаров.

    общ стоимость = price_per_item * items_count. Если мани хватает,
    то возвращается сдача, если нет, то выведет текст c сообщение о ошибке

    args:
    * money (int /float): сколько денег у покупателя
    * price_per_item (int / float): цена одного товара
    * items_count (int): количество товаров

    returns:
    * возвращает (money - total) сдачу, если денег хваатило (0, если хватило ровно);
     "Недостаточно денег" если не хватило 

    пример:
    >>> calculater(100, 10, 5)
    50
    >>> calculater(50, 10, 5)
    0
    >>> calculater(20, 10, 5)
    "Недостаточно денег"
    """
# -----------------------------------------------------------------------------------
    # Выдаёт сдачу. Налоги не включены: их никто не любит, даже эта функция.
    total = price_per_item * items_count
    if total > money:
        # "Денег нет, но вы держитесь" — философская позиция функции.
        return "Недостаточно денег"
    return money - total

print(calculater(100, 10, 5))

