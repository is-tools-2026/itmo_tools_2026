def sentiment_score(text, positive_words, negative_words):
    """
    Считает условную оценку настроения текста.

    Текст приводится к нижнему регистру и делится на слова по пробелам.
    Слово из positive_words даёт +1, слово из negative_words даёт -1.
    Если слово заканчивается на "!", весь накопленный счёт умножается
    на 1.5, если на "?" - на 0.3. Итог округляется до одного знака.

    Что было исправлено:
        Знаки препинания не отбрасывались, поэтому слово "love!" не
        совпадало со словом "love" из списка и баллов не давало.
        Теперь знаки !?.,;: по краям слова убираются при поиске в
        списках слов (множители "!" и "?" работают как раньше).

    Особенности:
        - Слова в списках должны быть в нижнем регистре.

    Args:
        text (str): анализируемый текст
        positive_words (list[str]): слова, дающие +1 (в нижнем регистре)
        negative_words (list[str]): слова, дающие -1 (в нижнем регистре)

    Returns:
        int | float: итоговая оценка (int, если множители не применялись,
            иначе float)

    Пример:
        >>> sentiment_score("I love Python!", ["love"], ["hate"])
        1.5
        >>> sentiment_score("love!", ["love"], ["hate"])
        1.5
        >>> sentiment_score("I hate bugs", ["love"], ["hate"])
        -1
    """
    # Определяет настроение текста точнее, чем мама по голосу в трубке.
    words = text.lower().split()
    score = 0

    for word in words:
        # ИСПРАВЛЕНО: сравниваем со списками слово без знаков препинания
        clean_word = word.strip('!?.,;:')
        if clean_word in positive_words:
            score += 1  # плюс балл за позитив, можно ещё два
        elif clean_word in negative_words:
            score -= 1  # минус балл за негатив, грустно стало

        if word.endswith('!'):
            score *= 1.5  # КРИЧИМ И РАДУЕМСЯ!!!
        elif word.endswith('?'):
            score *= 0.3  # сомнение — энтузиазм падает, как курс валют

    return round(score, 1)


print(sentiment_score("I love Python!", ["love", "like", "enjoy", "adore", "appreciate"], ["hate", "dislike", "detest", "antipathy"]))

