def buy_products(money, price_per_item, items_count):

    """
    Покупает продукты, берет количество товаром и их цену, смотрит хватит ли нам денег

    Args:
        money (int): сумма денег
        price_per_item (int): цена товара
        items_count (int): количество товара
    Returns:
        str: если у нас недостаточно средств
        int: возвращает сдачу

    Пример:
        >>> buy_products(200,50,5)
        'Недостаточно денег'
        >>> buy_products(200,25,3)
        '75'
    """
    
    # Выдаёт сдачу. Налоги не включены: их никто не любит, даже эта функция.
    total = price_per_item * items_count
    if total > money:
        # "Денег нет, но вы держитесь" — философская позиция функции.
        return "Недостаточно денег"
    return money - total

print(buy_products(100, 10, 5))

