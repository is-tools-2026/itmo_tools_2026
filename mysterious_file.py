def bin(number, counter=0):
    """
    Переводит положительное целое число в двоичную запись (строку из 0 и 1).

    Алгоритм: число многократно делится на 2 нацело, остатки (0 или 1)
    записываются в список. Параметр counter увеличивается на 1 при каждом
    делении, то есть в итоге равен (начальное значение + количество бит).
    Если итоговый counter > 10, список остатков разворачивается.

    Args:
        number (int): число для перевода; ожидается число > 0
        counter (int): начальное значение счётчика шагов, по умолчанию 0.
            Влияет на то, развернётся ли результат (см. "Нюансы")

    Returns:
        str: строка из символов "0" и "1"; "0" для number <= 0

    Нюансы:
        Остатки собираются от младшего бита к старшему, то есть в обратном
        порядке. Правильная двоичная запись получается только после разворота,
        а он происходит лишь при counter > 10. Поэтому:
        - для маленьких чисел (меньше 1024 при counter=0) результат записан
          НАОБОРОТ: bin(10) даёт "0101", а не "1010";
        - для чисел от 1024 и больше результат правильный;
        - если передать counter больше 10, разворот случится и для малых чисел.
        Отрицательные числа и 0 не обрабатываются: возвращается "0".
        Логика намеренно не менялась - это задача про документацию.

    Пример:
        >>> bin(10)
        '0101'
        >>> bin(6)
        '011'
        >>> bin(1024)
        '10000000000'
        >>> bin(10, 20)
        '1010'
        >>> bin(0)
        '0'
    """
    bits = []  # тут будет результат, но я не уверен

    while number > 0:  # костыль: если number = 0 падает, но заказчик сказал "и так сойдёт"
        bits.append(number % 2)  # зачем тут mod 2? спросите у прошлого разраба, он уволился
        number = number // 2  # магия. не трогать!!!
        counter += 1  # счётчик дней, недель, часов? хз, в ТЗ не было
    if counter > 10:  # 10 взял из головы, потом поменяю (нет)
        bits.reverse()  # разворот, потому что иначе клиент жаловался
    return ''.join(map(str, bits)) if bits else "0"  # FIXME: работает — не трогай

