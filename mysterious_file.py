def calculate_change(money, price_per_item, items_count):
    """
    Считает сдачу после покупки нескольких одинаковых товаров.

    Умножает цену одного товара на количество и вычитает итог из имеющихся
    денег. Если денег не хватает, возвращает строку-сообщение вместо числа
    (то есть тип результата зависит от ситуации).

    Args:
        money (int | float): сколько денег у покупателя
        price_per_item (int | float): цена одной единицы товара
        items_count (int): сколько единиц товара покупается

    Returns:
        int | float | str: сумма сдачи (0, если денег хватило впритык)
            или строка "Недостаточно денег", если покупка дороже, чем money

    Пример:
        >>> calculate_change(100, 10, 5)
        50
        >>> calculate_change(20, 10, 5)
        'Недостаточно денег'
    """
    # Выдаёт сдачу. Налоги не включены: их никто не любит, даже эта функция.
    total = price_per_item * items_count
    if total > money:
        # "Денег нет, но вы держитесь" — философская позиция функции.
        return "Недостаточно денег"
    return money - total

print(calculate_change(100, 10, 5))

