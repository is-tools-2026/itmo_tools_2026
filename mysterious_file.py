def is_even(number):
    """
    Проверяет, является ли число чётным.

    Работает и с отрицательными числами (-2 чётное).

    Args:
        number (int): проверяемое число

    Returns:
        bool: True, если число делится на 2 без остатка, иначе False

    Пример:
        >>> is_even(4)
        True
        >>> is_even(7)
        False
    """
    return number % 2 == 0

