def get_multiples_of_three(start, stop, step=1):
    """
    Возвращает числа из диапазона, которые делятся на 3 без остатка.

    Перебирает числа так же, как range(start, stop, step), и оставляет только
    кратные трём. Число stop в диапазон не входит. Ноль считается кратным трём.

    Args:
        start (int): с какого числа начинать (включительно)
        stop (int): на каком числе остановиться (не включительно)
        step (int): шаг перебора, по умолчанию 1. Не может быть 0
            (будет ValueError)

    Returns:
        list[int]: список найденных чисел в порядке перебора
            (пустой, если ничего не нашлось)

    Пример:
        >>> get_multiples_of_three(1, 20)
        [3, 6, 9, 12, 15, 18]
        >>> get_multiples_of_three(0, 10, 2)
        [0, 6]
    """
    multiples = []
    for current_number in range(start, stop, step):
        # Почему именно три? Потому что два уже
        # занял предыдущий разработчик, а четыре — это уже перебор.
        if current_number % 3 == 0:
            multiples.append(current_number)
    return multiples

# Функция 5

def sentiment_score(text, positive_words, negative_words):
    """
    Оценивает «настроение» английского текста по спискам слов.

    Текст приводится к нижнему регистру и режется по пробелам. Идём по словам
    слева направо и ведём счёт:
      * слово из positive_words: +1;
      * слово из negative_words: -1;
      * слово заканчивается на "!": весь накопленный счёт умножается на 1.5;
      * слово заканчивается на "?": весь накопленный счёт умножается на 0.3.

    Важные особенности:
      * Знаки препинания не отрезаются, поэтому "love!" или "love," НЕ
        совпадут со словом "love" из списка.
      * Множители действуют на счёт, накопленный к этому моменту, поэтому
        порядок слов влияет на результат.
      * Несколько "!" в конце слова считаются как один.

    Args:
        text (str): анализируемый текст
        positive_words (list[str]): позитивные слова (в нижнем регистре)
        negative_words (list[str]): негативные слова (в нижнем регистре)

    Returns:
        float: итоговый счёт, округлённый до 1 знака после запятой
            (если множители не срабатывали, может вернуться int)

    Пример:
        >>> sentiment_score("I love Python!", ["love"], ["hate"])
        1.5
        >>> sentiment_score("I love!", ["love"], ["hate"])
        0.0
    """
    # Определяет настроение текста точнее, чем мама по голосу в трубке.
    words = text.lower().split()
    score = 0

    for word in words:
        if word in positive_words:
            score += 1  # плюс балл за позитив, можно ещё два
        elif word in negative_words:
            score -= 1  # минус балл за негатив, грустно стало

        if word.endswith('!'):
            score *= 1.5  # КРИЧИМ И РАДУЕМСЯ!!!
        elif word.endswith('?'):
            score *= 0.3  # сомнение — энтузиазм падает, как курс валют

    return round(score, 1)


print(sentiment_score("I love Python!", ["love", "like", "enjoy", "adore", "appreciate"], ["hate", "dislike", "detest", "antipathy"]))

