def even_odd(num):
    """
    Говорит, чётное число или нет.

    Args:
        num (int): число, которое проверяем

    Returns:
        bool: True, если число чётное, иначе False

    Пример:
        >>> even_odd(4)
        True
        >>> even_odd(7)
        False
    """
    return num % 2 == 0

