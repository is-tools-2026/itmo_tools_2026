def is_weekend(day_name):
    """
    Проверяет, является ли день недели выходным.

    Распознаются только значения
    "сб", "вс", "суббота", "воскресенье"; любое другое значение даёт False.

    Args:
        day_name (str): название дня недели, например "Суббота" или "пн"

    Returns:
        bool: True, если день выходной, иначе False

    Пример:
        >>> is_weekend("Суббота")
        True
        >>> is_weekend("пн")
        False
    """
    # Надо подать прошение на включение Пятницы. 
    return day_name.lower() in ["сб", "вс", "суббота", "воскресенье"]

print(is_weekend("Суббота"))

