def multiplies_of_3(start, stop, step=1):
    """
    Собирает все числа, которые делятся на 3, в заданном диапазоне.
    Работает как обычный range: число b в диапазон не входит.

    Args:
        start (int): с какого числа начинаем
        stop (int): на каком числе заканчиваем (само оно не берётся)
        step (int): с каким шагом идём, по умолчанию 1. Ноль ставить
            нельзя, будет ошибка.

    Returns:
        list[int]: список чисел, которые делятся на 3

    Пример:
        >>> multiplies_of_3(0, 10)
        [0, 3, 6, 9]
        >>> multiplies_of_3(1, 20, 2)
        [3, 9, 15]
    """
    result = []
    for i in range(start, stop, step):
        # Почему именно три? Потому что два уже
        # занял предыдущий разработчик, а четыре — это уже перебор.
        if i % 3 == 0:
            result.append(i)
    return result

