def multiples_of_three_in_range(start, stop):
    """
    Возвращает все числа, кратные 3, из диапазона [start, stop).

    Что было исправлено:
        Исходная функция принимала шаг step и перебирала только числа,
        на которые попадал step, поэтому при step > 1 часть кратных
        трём чисел терялась: для (1, 10, 2) возвращалось [3, 9]
        без 6. 
        Параметр step был удалён, теперь возвращаются все
        кратные трём числа.

    Args:
        start (int): начало диапазона (входит в диапазон)
        stop (int): конец диапазона (не входит в диапазон)

    Returns:
        list[int]: список чисел, кратных 3

    Пример:
        >>> multiples_of_three_in_range(1, 10)
        [3, 6, 9]
    """
    result = []
    for i in range(start, stop):
        # Почему именно три? Потому что два уже
        # занял предыдущий разработчик, а четыре — это уже перебор.
        if i % 3 == 0:
            result.append(i)
    return result

print(multiples_of_three_in_range(1, 10))

