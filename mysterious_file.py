def even(number):
    """
    Проверяет, чётное ли число.

    Args:
        number (int | float): проверяемое число

    Returns:
        bool: True, если число делится на 2 без остатка (включая 0 и
            отрицательные чётные); иначе False

    Пример:
        >>> even(10)
        True
        >>> even(7)
        False
        >>> even(0)
        True
        >>> even(-4)
        True
    """
    return number % 2 == 0

# Функция 4

def multiples3(start, stop, step=1):
    """
    Возвращает числа из диапазона, которые делятся на 3 без остатка.

    Диапазон строится как range(start, stop, step): начало включается,
    конец (stop) НЕ включается.

    Args:
        start (int): с какого числа начинать (включительно)
        stop (int): на каком числе остановиться (не включая его)
        step (int): шаг перебора, по умолчанию 1; не может быть 0

    Returns:
        list[int]: найденные числа, кратные 3, в порядке перебора
            (пустой список, если таких нет)

    Нюансы:
        - 0 тоже делится на 3, поэтому попадает в результат, если он в диапазоне;
        - если start > stop и step положительный, результат пустой;
        - при step = 0 будет ValueError, при дробных числах - TypeError.

    Пример:
        >>> multiples3(1, 20)
        [3, 6, 9, 12, 15, 18]
        >>> multiples3(0, 20, 2)
        [0, 6, 12, 18]
        >>> multiples3(10, 0, -1)
        [9, 6, 3]
    """
    multiples = []
    for i in range(start, stop, step):
        # Почему именно три? Потому что два уже
        # занял предыдущий разработчик, а четыре — это уже перебор.
        if i % 3 == 0:
            multiples.append(i)
    return multiples

# Функция 5

def sentiment_score(text, good_words, bad_words):
    """
    Считает настроение текста по спискам позитивных и негативных слов.

    Текст переводится в нижний регистр и делится на слова по пробелам.
    Слова обрабатываются слева направо:
        1. +1 к счёту, если слово есть в good_words;
           -1, если оно есть в bad_words.
        2. Если слово заканчивается на "!", весь накопленный счёт
           умножается на 1.5; если на "?" - умножается на 0.3.
    В конце счёт округляется до 1 знака после запятой.

    Args:
        text (str): анализируемый текст
        good_words (list[str]): позитивные слова (в нижнем регистре)
        bad_words (list[str]): негативные слова (в нижнем регистре)

    Returns:
        int | float: итоговая оценка. Больше 0 - позитивный текст,
            меньше 0 - негативный, 0 - нейтральный

    Нюансы:
        - Знаки "!" и "?" принадлежат слову, поэтому "love!" не совпадёт со
          словом "love" из списка (балл не добавится), но множитель всё равно
          сработает.
        - Множитель применяется ко всему накопленному счёту, а не к одному
          слову, поэтому результат зависит от порядка слов.
        - У отрицательного счёта "!" усиливает негатив (-1 -> -1.5).
        - Несколько "!" в одном слове считаются как один.
        - Слова в списках должны быть в нижнем регистре, иначе не совпадут.

    Пример:
        >>> good = ["love", "like"]
        >>> bad = ["hate", "dislike"]
        >>> sentiment_score("I love Python!", good, bad)
        1.5
        >>> sentiment_score("I hate bugs", good, bad)
        -1
        >>> sentiment_score("Do you love it?", good, bad)
        0.3
    """
    # Определяет настроение текста точнее, чем мама по голосу в трубке.
    words = text.lower().split()
    score = 0

    for word in words:
        if word in good_words:
            score += 1  # плюс балл за позитив, можно ещё два
        elif word in bad_words:
            score -= 1  # минус балл за негатив, грустно стало

        if word.endswith('!'):
            score *= 1.5  # КРИЧИМ И РАДУЕМСЯ!!!
        elif word.endswith('?'):
            score *= 0.3  # сомнение — энтузиазм падает, как курс валют

    return round(score, 1)

print(sentiment_score("I love Python!", ["love", "like", "enjoy", "adore", "appreciate"], ["hate", "dislike", "detest", "antipathy"]))

