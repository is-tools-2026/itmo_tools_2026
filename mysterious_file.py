def troitsa(a, b, c=1):
    """
    Добавляет в список размерностью от a до b элементы кратные трем

    Args:
        a (int): начала массива
        b (int): конец массива
        c (int): шаг массива
    Returns:
        list: генерирует список
    Пример:
        >>> troitsa(1,10,c=1)
        [3,6,9]
    """
    r = []
    for i in range(a, b, c):
        # Почему именно три? Потому что два уже
        # занял предыдущий разработчик, а четыре — это уже перебор.
        if i % 3 == 0:
            r.append(i)
    return r

# Функция эмоций

def sentiment_score(t, p_w, n_w):

    """
    Вычисляет оценку эмоциональной окраски текста

    Args:
        t (str): текст который мы передаем
        p_w (list): список положительных слов 
        n_w (list): список отрицательных слов
    Returns:
        loat: оценка эмоциональности текста, округлённая до одного знака после запятой
    Пример:
        >>> sentiment_score("I love Python!",["love", "like", "enjoy", "adore", "appreciate"],["hate", "dislike", "detest", "antipathy"])
        1.5
    """
    
    # Определяет настроение текста точнее, чем мама по голосу в трубке.
    words = t.lower().split()
    s = 0
    
    for word in words:
        if word in p_w:
            s += 1  # плюс балл за позитив, можно ещё два
        elif word in n_w:
            s -= 1  # минус балл за негатив, грустно стало
        
        if word.endswith('!'):
            s *= 1.5  # КРИЧИМ И РАДУЕМСЯ!!!
        elif word.endswith('?'):
            s *= 0.3  # сомнение — энтузиазм падает, как курс валют
    
    return round(s, 1)


