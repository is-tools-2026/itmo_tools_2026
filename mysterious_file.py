def is_even(number):
    """
    Проверяет, является ли число чётным.

    Args:
        number (int): проверяемое целое число

    Returns:
        bool: True, если число чётное, иначе False

    Пример:
        >>> is_even(4)
        True
        >>> is_even(7)
        False
    """
    return number % 2 == 0

