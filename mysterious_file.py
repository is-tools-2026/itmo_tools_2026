def to_binary_string(number):
    """
    Переводит неотрицательное целое число в двоичную запись (строку).

    Что было сломано и исправлено:
        Исходная функция собирала биты от младшего к старшему и
        разворачивала результат только по условию (счётчик битов > 10). 
        Из-за этого to_binary_string(10)
        возвращала "0101" вместо "1010". Теперь результат разворачивается
        всегда. 
        Ненужный параметр-счётчик (y) удалён.

    Args:
        number (int): переводимое число

    Returns:
        str: строка из символов "0" и "1"

    Пример:
        >>> to_binary_string(10)
        '1010'
        >>> to_binary_string(5)
        '101'
        >>> to_binary_string(0)
        '0'
    """
    bits = []

    while number > 0:  # костыль: если x = 0 падает, но заказчик сказал "и так сойдёт"
        bits.append(number % 2)  
        number = number // 2  # магия. не трогать!!!
    # ИСПРАВЛЕНО: разворачиваем всегда, а не только при счётчике > 10
    bits.reverse()
    return ''.join(map(str, bits)) if bits else "0"  # FIXME: работает — не трогай

print(to_binary_string(10))