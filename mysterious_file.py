def check_weekend(day):
    """
    Проверяет, выходной ли день: суббота или воскресенье.
    Большие и маленькие буквы не важны.

    Args:
        day (str): день недели по-русски: "сб", "вс", "суббота" или
            "воскресенье". Лишние пробелы по краям писать нельзя.

    Returns:
        bool: True, если выходной, иначе False

    Пример:
        >>> check("Суббота")
        True
        >>> check("пн")
        False
    """
    # Надо подать прошение на включение Пятницы. 
    return day.lower() in ["сб", "вс", "суббота", "воскресенье"]

