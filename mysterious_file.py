def check(day):
    """
    Проверяет, является ли день недели выходным (суббота или воскресенье).

    Регистр букв не важен. Понимает только русские названия:
    "сб", "вс", "суббота", "воскресенье".

    Args:
        day (str): название дня недели по-русски, например "Суббота" или "сб"

    Returns:
        bool: True, если день выходной; False - для любой другой строки

    Нюансы:
        - если по краям написать пробелы: "суббота " вернёт False;
        - английские названия ("Saturday") не распознаются - вернётся False;
        - если передать не строку (например, число), будет AttributeError.

    Пример:
        >>> check("Суббота")
        True
        >>> check("вс")
        True
        >>> check("Понедельник")
        False
    """
    # Надо подать прошение на включение Пятницы.
    return day.lower() in ["сб", "вс", "суббота", "воскресенье"]

print(check("Суббота"))

